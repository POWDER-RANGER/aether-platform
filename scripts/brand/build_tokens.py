"""Build interfaces/shared/design/tokens.css from interfaces/shared/design/tokens.json and check WCAG contrast.

Usage:
    python scripts/brand/build_tokens.py          # write interfaces/shared/design/tokens.css, print contrast table
    python scripts/brand/build_tokens.py --check  # exit 1 if tokens.css is stale or a contrast pair fails

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DESIGN = ROOT / "interfaces" / "shared" / "design"
SRC = DESIGN / "tokens.json"
OUT = DESIGN / "tokens.css"
PRODUCTS = ("aether", "prrex", "aacp")


def _lum(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    chans = [int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in chans]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(fg: str, bg: str) -> float:
    a, b = sorted((_lum(fg), _lum(bg)), reverse=True)
    return (a + 0.05) / (b + 0.05)


def load() -> dict:
    return json.loads(SRC.read_text(encoding="utf-8"))


def contrast_report(t: dict) -> list[tuple[str, str, str, str, float, float, bool]]:
    rows = []
    for scheme in ("dark", "light"):
        base = t["color"][scheme]
        for pair in t["contrast"]:
            products = PRODUCTS if pair.get("per_product") else ("-",)
            for p in products:
                pal = dict(base)
                if p != "-":
                    pal.update(t["product"][p][scheme])
                fg, bg = pal[pair["fg"]], pal[pair["bg"]]
                r = contrast(fg, bg)
                rows.append(
                    (
                        scheme,
                        p,
                        pair["fg"],
                        pair["bg"],
                        round(r, 2),
                        pair["min"],
                        r >= pair["min"],
                    )
                )
    return rows


def _vars(d: dict, prefix: str = "", indent: str = "  ") -> list[str]:
    return [f"{indent}--{prefix}{k}:{v};" for k, v in d.items()]


def render_css(t: dict) -> str:
    dark, light = t["color"]["dark"], t["color"]["light"]
    prod = t["product"]
    out = [
        (
            f"/* {t['meta']['name']} {t['meta']['version']}. GENERATED by scripts/brand/build_tokens.py "
            "from interfaces/shared/design/tokens.json. Do not edit by hand. */"
        ),
        ":root{",
        *_vars(dark),
        *_vars(prod["aether"]["dark"]),
        *_vars(t["space"], "s-"),
        *_vars(t["radius"], "r-"),
        *_vars(t["border"], "b-"),
        *_vars(t["font"]),
        *_vars(t["size"], "fs-"),
        *_vars(t["target"], "target-"),
        *_vars(t["motion"], "motion-"),
        "  color-scheme:dark;",
        "}",
    ]
    for p in PRODUCTS:
        out += [f'[data-product="{p}"]{{', *_vars(prod[p]["dark"]), "}"]
    # Light: follows the OS unless data-theme="dark" pins dark; data-theme="light" pins light.
    out += ["@media (prefers-color-scheme:light){", '  :root:not([data-theme="dark"]){']
    out += [
        *_vars(light, indent="    "),
        *_vars(prod["aether"]["light"], indent="    "),
        "    color-scheme:light;",
        "  }",
    ]
    for p in PRODUCTS:
        out += [
            f'  :root:not([data-theme="dark"]) [data-product="{p}"]{{',
            *_vars(prod[p]["light"], indent="    "),
            "  }",
        ]
    out += ["}"]
    out += [
        ':root[data-theme="light"]{',
        *_vars(light),
        *_vars(prod["aether"]["light"]),
        "  color-scheme:light;",
        "}",
    ]
    for p in PRODUCTS:
        out += [
            f':root[data-theme="light"] [data-product="{p}"]{{',
            *_vars(prod[p]["light"]),
            "}",
        ]
    out += [
        "/* Breakpoints (media queries cannot read custom properties; use these values literally): "
        + ", ".join(f"{k} >= {v}" for k, v in t["breakpoint"].items())
        + " */"
    ]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    t = load()
    css = render_css(t)
    rows = contrast_report(t)
    failed = [r for r in rows if not r[6]]
    for r in rows:
        print(f"{r[0]:5} {r[1]:6} {r[2]:>7} on {r[3]:<6} {r[4]:5.2f} (min {r[5]}) {'ok' if r[6] else 'FAIL'}")
    if args.check:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8") != css
        if stale:
            print("interfaces/shared/design/tokens.css is stale: run python scripts/brand/build_tokens.py")
        return 1 if (stale or failed) else 0
    OUT.write_text(css, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
