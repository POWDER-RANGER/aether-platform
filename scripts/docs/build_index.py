from __future__ import annotations
import json
from pathlib import Path
LABELS={'VERIFIED','PARTIALLY VERIFIED','UNVERIFIED','FAILED','BLOCKED','NOT IMPLEMENTED'}
def build(root):
 rows=[];e=root/'evidence'
 if e.exists():
  for p in sorted(x for x in e.rglob('*') if x.is_file()):
   try:d=json.loads(p.read_text(encoding='utf-8')) if p.suffix.lower()=='.json' else {}
   except (OSError,json.JSONDecodeError):d={}
   run=str(d.get('run_id') or d.get('identity',{}).get('run_id') or '');date=str(d.get('timestamp_utc') or d.get('date') or '')[:10];crit=str(d.get('criterion') or d.get('scenario') or p.parent.name);v=str(d.get('evidence_label') or d.get('status') or d.get('outcome') or '').upper();rows.append((p.relative_to(root).as_posix(),run,date,crit,v if v in LABELS else ''))
 lines=['# Evidence index','','Generated by scripts/docs/build_index.py. Do not hand-edit.','','| File | Run ID | Date | Criterion / scenario | Evidence label |','|---|---|---|---|---|']
 lines += ['| '+' | '.join(v.replace('|','\\|') for v in row)+' |' for row in rows] or ['| *(no evidence files found)* | | | | |']
 return '\n'.join(lines)+'\n'
def main():
 root=Path(__file__).resolve().parents[2];p=root/'docs/evidence/INDEX.md';p.parent.mkdir(parents=True,exist_ok=True);p.write_text(build(root),encoding='utf-8');return 0
if __name__=='__main__':raise SystemExit(main())
