from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

LABELS = {"VERIFIED", "PARTIALLY VERIFIED", "UNVERIFIED", "FAILED", "BLOCKED", "NOT IMPLEMENTED"}


def build(root: Path) -> str:
    evidence = root / "evidence"
    rows = []
    if evidence.exists():
        for path in sorted(item for item in evidence.rglob("*") if item.is_file()):
            try:
                data = json.loads(path.read_text(encoding="utf-8")) if path.suffix.lower() == ".json" else {}
            except (OSError, json.JSONDecodeError):
                data = {}
            parts = path.relative_to(evidence).parts
            run_id = str(data.get("run_id") or data.get("identity", {}).get("run_id") or (parts[1] if len(parts) >= 3 else (path.stem if len(parts) == 2 else "")))
            date = str(data.get("timestamp_utc") or data.get("date") or "")
            if not date:
                date = datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).date().isoformat()
            criterion = str(data.get("criterion") or data.get("scenario") or (parts[0] if parts else ""))
            candidate = str(data.get("evidence_label") or data.get("status") or data.get("outcome") or "").upper()
            label = candidate if candidate in LABELS else ""
            rows.append((path.relative_to(root).as_posix(), run_id, date[:10], criterion, label))
    lines = [
        "# Evidence index",
        "",
        "Generated by scripts/docs/build_index.py. Do not hand-edit.",
        "",
        "| File | Run ID | Date | Criterion / scenario | Evidence label |",
        "|---|---|---|---|---|",
    ]
    lines.extend("| " + " | ".join(value.replace("|", "\\|") for value in row) + " |" for row in rows)
    if not rows:
        lines.append("| *(no evidence files found)* | | | | |")
    return "\n".join(lines) + "\n"


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    output = root / "docs/evidence/INDEX.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build(root), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
